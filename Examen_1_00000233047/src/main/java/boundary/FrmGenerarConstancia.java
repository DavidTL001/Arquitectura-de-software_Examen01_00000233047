    // Configura eventos 
    private void configurarEventos() {
    
        txtAreaBuscar.addKeyListener(new java.awt.event.KeyAdapter() {
            @Override
            public void keyReleased(java.awt.event.KeyEvent evt) {
                txtAreaBuscarKeyReleased(evt);
            }
        });

    
        txtAreaBuscar.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (txtAreaBuscar.getText().equals("buscar...")) {
                    txtAreaBuscar.setText("");
                    txtAreaBuscar.setForeground(Color.BLACK);
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (txtAreaBuscar.getText().trim().isEmpty()) {
                    txtAreaBuscar.setText("buscar...");
                    txtAreaBuscar.setForeground(new Color(102, 102, 102));
                }
            }
        });

   
        tableSugerencias.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                tableSugerenciasMouseClicked(evt);
            }
        });
    }

    // Busqueda de sugerencias
    private void txtAreaBuscarKeyReleased(java.awt.event.KeyEvent evt) {
        String textoBuscado = txtAreaBuscar.getText().trim();

        if (textoBuscado.isEmpty() || textoBuscado.equals("buscar...")) {
            limpiarTabla();
            ttAreaVisualizacion.setText("");
            btnGenerarConstancia.setEnabled(false);
            return;
        }

        List<Alumno> resultados = control.buscarAlumnosPorID(textoBuscado);
        DefaultTableModel model = (DefaultTableModel) tableSugerencias.getModel();
        model.setRowCount(0);

        for (Alumno a : resultados) {
            model.addRow(new Object[]{a.getIdAlumno()});
        }

        // Si no hay coincidencias 
        if (resultados.isEmpty()) {
            ttAreaVisualizacion.setText("=========================================\n"
                    + "         ALERTA: ID NO ENCONTRADO        \n"
                    + "=========================================\n\n"
                    + "El ID ingresado no se encuentra registrado\n"
                    + "en el sistema.");
            btnGenerarConstancia.setEnabled(false);
            alumnoSeleccionado = null;
            inscripcionSeleccionada = null;
        }
    }

    // Generación de previsualización
    private void tableSugerenciasMouseClicked(java.awt.event.MouseEvent evt) {
        int fila = tableSugerencias.getSelectedRow();
        if (fila != -1) {
            Object valorCelda = tableSugerencias.getValueAt(fila, 0);
            if (valorCelda != null) {
                String idSeleccionado = valorCelda.toString();
                inscripcionSeleccionada = control.obtenerInscripcionVigente(idSeleccionado);

                if (inscripcionSeleccionada != null) {
                    alumnoSeleccionado = inscripcionSeleccionada.getAlumno();

                    String textoPrevis = control.construirTextoPrevisualizacion(alumnoSeleccionado, inscripcionSeleccionada);
                    ttAreaVisualizacion.setText(textoPrevis);

                    btnGenerarConstancia.setEnabled(true);
                }
            }
        }
    }

    private void limpiarTabla() {
        DefaultTableModel model = (DefaultTableModel) tableSugerencias.getModel();
        model.setRowCount(0);
    }

